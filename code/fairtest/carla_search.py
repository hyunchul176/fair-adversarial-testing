"""E7: attack search run inside CARLA against physically simulated SUTs, including a third-party SUT (BehaviorAgent).

Plan space and optimiser as B11/B13 (5-D continuous plan, CMA-ES, population 6, SUT budget 36). For a candidate
plan the adversary's trajectory is generated by the highway-env generator (its motion depends only on the plan), then
the SUT and the R157 CC reference are both simulated in CARLA (`carla_replay.run`).
  fair     f = SUT min gap + 20 [CARLA-CC collides] - 5 [fair failure]; started at the stored R157-boundary plan;
           stops at the first fair failure (the agent's refinement stage, run in CARLA)
  collide  f = SUT min gap; started at the box centre; stops at the first SUT collision, which is then judged by
           the CARLA-CC post hoc (generic falsification + CARS-style attribution)
  fair_g4  (GP-BO only) f = SUT min gap + 20 [CARLA-CC collides] + 10 max(0, 0.5 - CARLA-CC clearance) - 5 [robust fair
           failure]; stops at the first ROBUST fair failure (front contact, contact_dx >= 3.5 m, CC clearance >= 0.5 m)
  fair_g4g (GP-BO only, final agent v2) fair_g4 plus the RL guards in plan space, judged on the plan's highway-env twin
           (the adversary's motion depends only on the plan): no lateral retreat > 0.2 m after the CC perception
           threshold (G1) and a realistic cut-in, realism exceedance <= 1 IQR (G2); penalties as b23_search _g4g

  python -m fairtest.carla_search OUT.jsonl --cont STORED_B11.jsonl --kinds ladder:following:0,ba:normal \
         --objectives fair,collide [--cases 0:31] [--port 2000]
"""
from __future__ import annotations

import argparse
import json
import math
import os
import time

import numpy as np

from fairtest import devboot  # noqa: F401


def adversary_row(case, theta):
    from fairtest.b11_search import ContinuousPlan
    return trajectory_row(case, ContinuousPlan.from_theta(theta))


def trajectory_row(case, plan):
    """highway-env adversary trajectory of a plan (target = omniscient braker, so the episode runs the full horizon)."""
    from fairtest import runner
    row = runner.run_episode(case, plan, 'oracle_t0', 0., keep_trace=True)
    g_init = row['physical_initial_state'][0]  # trace row k is the state after tick k: prepend the t = 0 state
    tr = [dict(t=0., x=g_init['x'], y=g_init['y'], vx=g_init['vx'], vy=g_init['vy'], heading=g_init['heading'])]
    tr += [dict(t=round((k + 1) * .1, 1), x=s['generator']['x'], y=s['generator']['y'], vx=s['generator']['vx'],
                vy=s['generator']['vy'], heading=s['generator']['heading']) for k, s in enumerate(row['trace'])]
    while len(tr) < 121:
        last = tr[-1]
        tr.append(dict(t=round(last['t'] + .1, 1), x=last['x'] + last['vx'] * .1, y=last['y'] + last['vy'] * .1,
                       vx=last['vx'], vy=last['vy'], heading=last['heading']))
    t0 = case['physical_initial_state'][1]
    return bool(row['maneuver_valid_precontact']), dict(sut0=dict(x=t0['x'], y=t0['y'], vx=t0['vx'], vy=t0['vy']),
                                    cruise=case['event']['metrics']['p10']['target_speed'], trajectory=tr)


def twin_guards(case, theta):
    """(feint, realism exceedance) of a plan from its highway-env CC counterfactual (b23_search.guard_terms)."""
    from fairtest import runner
    from fairtest.b11_search import ContinuousPlan
    from fairtest.b23_search import guard_terms
    plan = ContinuousPlan.from_theta(theta)
    raw = runner.run_episode(case, plan, 'cc_r157', 0., keep_trace=True)
    return guard_terms(raw['trace'], runner.compact(raw, case, plan, 'cc_r157', 0.)['features'])


def carla_eval(world, road, bp, base, case, kind, objective, theta):
    """One SUT query in CARLA (plus the CARLA-CC when needed): (f, record), or (60, None) for an invalid plan (no query)."""
    from fairtest.carla_replay import run
    valid, row = adversary_row(case, theta)
    if not valid:
        return 60., None
    s = run(world, road, bp, row, kind, base)
    gap = -1. if s['contact'] else (50. if s['min_gap'] is None else s['min_gap'])
    judged = objective in ('fair', 'fair_g4', 'fair_g4g')
    cc = run(world, road, bp, row, 'cc', base) if (judged or s['contact']) else None
    cc_contact = bool(cc and cc['contact'])
    fair = bool(s['contact'] and cc is not None and not cc_contact)
    clear = None if cc is None else cc['min_clearance']
    robust = bool(fair and (s.get('contact_dx') or 0.) >= 3.5 and clear is not None and clear >= .5)
    feint, exc, guarded = None, None, None
    if objective == 'fair_g4g':
        feint, exc = twin_guards(case, theta)
        guarded = bool(robust and not feint and exc is not None and exc <= 1.)
        pen = (10. if feint else 0.) + (10. if exc is None else 5. * max(0., exc - 1.))
        f = gap + (20. if cc_contact else 10. * max(0., .5 - clear) + pen) - (5. if guarded else 0.)
    elif objective == 'fair_g4':
        f = gap + (20. if cc_contact else 10. * max(0., .5 - clear)) - (5. if robust else 0.)
    else:
        f = gap + (20. if cc_contact and objective == 'fair' else 0.) - (5. if fair and objective == 'fair' else 0.)
    return f, dict(f=f, theta=[float(x) for x in theta], sut_contact=bool(s['contact']), cc_contact=cc_contact, fair=fair,
                   robust=robust, guarded=guarded, feint=feint, realism_exceedance=exc, sut_min_acc=s['sut_min_acc'],
                   v0_error=s['v0_error'], contact_dx=s.get('contact_dx'), cc_min_clearance=clear)


def search_bo(world, road, bp, base, case, kind, objective, x0, budget=36):
    """GP-BO with expected improvement from the R157-boundary plan (settings of b23_search)."""
    from sklearn.gaussian_process import GaussianProcessRegressor
    from sklearn.gaussian_process.kernels import ConstantKernel, Matern, WhiteKernel
    from fairtest.b11_search import HIGH, LOW
    from fairtest.b23_search import N_CAND, N_INIT, _ei
    rng = np.random.default_rng(int(case['case_id']) + 1)
    scale = HIGH - LOW
    init = [np.clip((np.asarray(x0) - LOW) / scale, 0, 1)]
    while len(init) < N_INIT:
        init.append(rng.random(5))
    X, y, n, it, best, found = [], [], 0, 0, None, None
    while n < budget and found is None and it < 4 * budget:
        it += 1
        if len(X) < len(init):
            x = init[len(X)]
        else:
            gp = GaussianProcessRegressor(ConstantKernel(1.) * Matern(length_scale=np.full(5, .3), nu=2.5) + WhiteKernel(1e-3),
                                          normalize_y=True, n_restarts_optimizer=0, random_state=0)
            gp.fit(np.array(X), np.array(y))
            xb = np.array(X)[int(np.argmin(y))]
            cand = np.vstack([rng.random((N_CAND, 5)), np.clip(xb + rng.normal(0, .08, (N_CAND // 4, 5)), 0, 1)])
            mu, sd = gp.predict(cand, return_std=True)
            x = cand[int(np.argmax(_ei(mu, sd, float(np.min(y)))))]
        f, rec = carla_eval(world, road, bp, base, case, kind, objective, LOW + x * scale)
        X.append(x)
        y.append(f)
        if rec is None:
            continue
        n += 1
        if best is None or f < best['f']:
            best = rec
        if ((objective == 'fair' and rec['fair']) or (objective == 'fair_g4' and rec['robust'])
                or (objective == 'fair_g4g' and rec['guarded']) or (objective == 'collide' and rec['sut_contact'])):
            found = dict(query=n, fair=rec['fair'], robust=rec['robust'], guarded=rec['guarded'], cc_contact=rec['cc_contact'],
                         theta=rec['theta'], contact_dx=rec['contact_dx'], cc_min_clearance=rec['cc_min_clearance'],
                         feint=rec['feint'], realism_exceedance=rec['realism_exceedance'])
    return dict(best=best, found=found, sut_queries=n)


def search(world, road, bp, base, case, kind, objective, x0, budget=36, sigma=.8):
    import cma
    from fairtest.b11_search import HIGH, LOW
    from fairtest.carla_replay import run
    scale = HIGH - LOW
    es = cma.CMAEvolutionStrategy(list(np.clip((np.asarray(x0) - LOW) / scale, 0, 1)), sigma / 4.,
                                  dict(bounds=[0, 1], popsize=6, seed=int(case['case_id']) + 1, verbose=-9))
    n, best, found = 0, None, None
    while not es.stop() and n < budget and found is None:
        xs, fs = es.ask(), []
        for x in xs:
            theta = LOW + np.asarray(x) * scale
            valid, row = adversary_row(case, theta)
            if not valid:
                fs.append(60.)
                continue
            s = run(world, road, bp, row, kind, base)
            n += 1
            gap = -1. if s['contact'] else (50. if s['min_gap'] is None else s['min_gap'])
            cc = run(world, road, bp, row, 'cc', base) if (objective == 'fair' or s['contact']) else None
            cc_contact = bool(cc and cc['contact'])
            fair = bool(s['contact'] and cc is not None and not cc_contact)
            f = gap + (20. if cc_contact and objective == 'fair' else 0.) - (5. if fair and objective == 'fair' else 0.)
            fs.append(f)
            if best is None or f < best['f']:
                best = dict(f=f, theta=theta.tolist(), sut_contact=bool(s['contact']), cc_contact=cc_contact, fair=fair,
                            sut_min_acc=s['sut_min_acc'], v0_error=s['v0_error'])
            if (objective == 'fair' and fair) or (objective == 'collide' and s['contact']):
                found = dict(query=n, fair=fair, cc_contact=cc_contact, theta=theta.tolist(),  # G4 fields of this query
                             contact_dx=s.get('contact_dx'), cc_min_clearance=None if cc is None else cc['min_clearance'])
                break
            if n >= budget:
                break
        if found is None and len(fs) == len(xs):
            es.tell(xs, fs)
    return dict(best=best, found=found, sut_queries=n)


def main(a):
    from fairtest.b11_search import HIGH, LOW
    from fairtest.carla_replay import BLUEPRINT, Road, connect
    from fairtest.runner import _STATE, _init
    _init()
    base = _STATE['base']
    boundary = {}
    for line in open(a.cont, encoding='utf-8'):
        r = json.loads(line)
        b = (r.get('cc_boundary') or {}).get('best')
        boundary[r['case_id']] = b['theta'] if b and not b['cc_contact'] else None
    ids = sorted(c for c, v in _STATE['cases'].items() if a.partition == 'all' or v['event'].get('partition') == a.partition)
    lo, hi = (int(x) for x in a.cases.split(':')) if a.cases else (0, len(ids))
    ids = ids[lo:hi]
    if a.resume and os.path.exists(a.out):  # restart after a CARLA server crash: skip finished cases
        done = {json.loads(l)['case_id'] for l in open(a.out, encoding='utf-8') if l.strip()}
        ids = [c for c in ids if c not in done]
    world = connect(a.port)
    road = Road(world)
    bp = world.get_blueprint_library().find(BLUEPRINT)
    try:
        with open(a.out, 'a', encoding='utf-8') as f:
            for i, c in enumerate(ids):
                case = _STATE['cases'][c]
                out = dict(case_id=c, runs={})
                t0 = time.time()
                for kind in a.kinds.split(','):
                    for objective in a.objectives.split(','):
                        x0 = boundary.get(c) if objective in ('fair', 'fair_g4', 'fair_g4g') and boundary.get(c) is not None else (LOW + HIGH) / 2
                        try:
                            fn = search_bo if a.optimiser == 'bo' else search
                            out['runs'][f'{objective}|{kind}'] = fn(world, road, bp, base, case, kind, objective, x0, a.budget)
                        except Exception as e:  # recorded, never dropped
                            out['runs'][f'{objective}|{kind}'] = dict(error=f'{type(e).__name__}: {e}')
                out['seconds'] = round(time.time() - t0, 1)
                f.write(json.dumps(out) + '\n')
                f.flush()
                print(json.dumps(dict(done=i + 1, of=len(ids), case=c, seconds=out['seconds'])), flush=True)
    finally:
        s = world.get_settings()
        s.synchronous_mode = False
        world.apply_settings(s)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--cont', required=True)
    ap.add_argument('--kinds', default='ladder:following:0,ladder:rss_sut:0,ba:cautious,ba:normal')
    ap.add_argument('--objectives', default='fair,collide')
    ap.add_argument('--partition', default='development')
    ap.add_argument('--cases', help='slice start:end of the sorted case ids')
    ap.add_argument('--budget', type=int, default=36)
    ap.add_argument('--port', type=int, default=2000)
    ap.add_argument('--resume', action='store_true', help='skip cases already in OUT')
    ap.add_argument('--optimiser', default='cmaes', choices=('cmaes', 'bo'))
    args = ap.parse_args()
    if {'fair_g4', 'fair_g4g'} & set(args.objectives.split(',')) and args.optimiser != 'bo':
        raise SystemExit('objectives fair_g4/fair_g4g are implemented for --optimiser bo only')
    main(args)
