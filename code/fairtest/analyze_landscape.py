"""Analyse the B7 development landscape: fair (CC-preventable) SUT failures vs realism.

Definitions (development metrics, B7 design note):
  * valid: generator pre-contact physical audit passed (unchanged B2 audit).
  * SUT failure: valid and intended-pair contact with the SUT target.
  * CC-preventable: the same (case, plan) run against the R157 CC driver ends without contact.
  * fair failure: SUT failure and CC-preventable. Unpreventable = SUT failure and CC contact.
  * nominal exclusion: cases whose never-enter plan already produces contact or TTC<1.5 for
    that SUT (risk not generated by the adversary).
  * realism: per-feature two-sided empirical tail vs exposed natural cut-ins; max_exceedance is
    the largest excess beyond natural p1..p99 in IQR units (0 = inside for every feature).
"""
from __future__ import annotations

import argparse
import collections
import json
import math
from pathlib import Path

import numpy as np

from fairtest.features import Realism

SUTS = (('following', 0.), ('following', .5), ('following', 1.), ('reference_idm', 0.),
        ('following_aeb', 0.), ('following_aeb', .5))


def key(policy):
    return policy.get('name')


def load(path):
    rows = [json.loads(l) for l in Path(path).read_text(encoding='utf-8').splitlines() if l.strip()]
    errors = [r for r in rows if 'error' in r]
    return [r for r in rows if 'error' not in r], errors


def analyse(rows, realism=None):
    realism = realism or Realism()
    by = collections.defaultdict(dict)  # (case, policy) -> {(target,H): row}
    for r in rows:
        by[(r['case_id'], key(r['policy']))][(r['target'], r['H'])] = r
    suts = [s for s in SUTS if any(s in v for v in by.values())]
    cases = sorted({c for c, _ in by})
    policies = sorted({p for _, p in by})
    nominal = 'plan_enever_pre0_post0_dgrid'
    # realism per (case, policy) from the CC run (generator motion is open-loop for plans)
    real = {}
    for k, v in by.items():
        ref = v.get(('cc_r157', 0.)) or next(iter(v.values()))
        real[k] = realism.score(ref['features']) if ref['features'].get('cut_in') else None
    out = dict(cases=len(cases), policies=len(policies), suts={})
    for s in suts:
        name = f'{s[0]}_H{s[1]:g}'
        excluded = set()
        for c in cases:
            nom = by.get((c, nominal), {}).get(s)
            if nom is None or nom['contact'] or nom['ttc_event'] or nom['initial_event']:
                excluded.add(c)
        eligible = [c for c in cases if c not in excluded]
        per_policy = collections.Counter()
        unprev_policy = collections.Counter()
        case_best = {}
        for (c, p), v in by.items():
            if c in excluded or s not in v or ('cc_r157', 0.) not in v:
                continue
            r, cc = v[s], v[('cc_r157', 0.)]
            if not r['valid']:
                continue
            if r['contact'] and not cc['contact']:
                per_policy[p] += 1
                sc = real[(c, p)]
                e = sc['max_exceedance'] if sc else math.inf
                if c not in case_best or e < case_best[c][0]:
                    case_best[c] = (e, p)
            elif r['contact'] and cc['contact']:
                unprev_policy[p] += 1
        thresholds = [0., .25, .5, 1., 2., 4., math.inf]
        curve = {('inf' if math.isinf(t) else f'{t:g}'): sum(1 for e, _ in case_best.values() if e <= t)
                 for t in thresholds}
        fixed = {p: n for p, n in per_policy.items() if p.startswith('plan_')}
        best_fixed = max(fixed.items(), key=lambda x: x[1]) if fixed else (None, 0)
        out['suts'][name] = dict(
            eligible_cases=len(eligible), excluded_nominal_risk=len(excluded),
            oracle_cases_with_fair_failure=len(case_best),
            fair_failure_cases_by_max_exceedance=curve,
            b5_fair=per_policy.get('b5_braking_entry', 0), b5_unpreventable=unprev_policy.get('b5_braking_entry', 0),
            fixed2s_fair=per_policy.get('plan_e2_pre-3_post-3_dgrid', 0),
            fixed2s_unpreventable=unprev_policy.get('plan_e2_pre-3_post-3_dgrid', 0),
            best_single_plan=dict(name=best_fixed[0], fair=best_fixed[1]),
            top_plans=[dict(name=p, fair=n, unpreventable=unprev_policy.get(p, 0))
                       for p, n in per_policy.most_common(8)])
    return out


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('landscape')
    ap.add_argument('--out')
    a = ap.parse_args()
    ok, err = load(a.landscape)
    res = analyse(ok)
    res['rows'], res['errors'] = len(ok), len(err)
    text = json.dumps(res, indent=1)
    print(text)
    if a.out:
        Path(a.out).write_text(text + '\n', encoding='utf-8')
