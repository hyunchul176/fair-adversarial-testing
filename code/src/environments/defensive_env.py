"""
Defensive RL Environment for Normal Driving

PURPOSE:
    Gymnasium environment wrapping highway-env for training a defensive
    autonomous vehicle.  The ego agent learns to drive safely in normal IDM
    traffic: avoid collisions, maintain lane center, and sustain highway speed.

RESEARCH CONTEXT:
    This environment trains a "victim" AV that serves as the ego vehicle during
    adversarial scenario evaluation.  A well-trained defensive agent is needed
    so that adversarial scenarios generated by the ASG framework are tested
    against a competent (not random) AV policy.  Without a reasonable defensive
    policy, collision rates would be meaninglessly high and the BRS metric
    would lack discriminative power.

ARCHITECTURE:
    RL Agent (PPO) --> action [acceleration, steering] --> Ego Vehicle
                         |  accel in [-5, 5] m/s^2
                         |  steering in [-0.3, 0.3]
                         v
                highway-env step (IDM traffic, no adversarial NPCs)
                         |
                         v
              obs (5-vehicle kinematics), reward (defensive)

OBSERVATION SPACE:
    5-vehicle Kinematics matrix from highway-env, flattened to 25D.
    Each vehicle: [x, y, vx, vy, heading] (5 features x 5 vehicles).
    Values are normalized by highway-env's built-in normalization.

ACTION SPACE:
    Continuous 2D: [acceleration, steering]
    acceleration in [-5, 5] m/s^2, steering in [-0.3, 0.3]

REWARD:
    R = R_collision + R_lane_keeping + R_speed
    - R_collision:    -10.0 on crash (terminal)
    - R_lane_keeping: +0.1 * (1 - |lateral_offset| / half_lane_width)
    - R_speed:        +0.1 if ego speed in [20, 30] m/s, else -0.1
"""

from __future__ import annotations

import logging
from typing import Any, Dict, Optional, Tuple

import gymnasium
import numpy as np
from gymnasium import spaces

logger = logging.getLogger(__name__)


def _try_import_highway_env():
    """Lazy-import highway_env to allow importing this module without it installed."""
    try:
        import highway_env  # noqa: F401
        return highway_env
    except ImportError as exc:
        raise ImportError(
            "highway-env not found. Install with: pip install highway-env"
        ) from exc


class DefensiveRLEnv(gymnasium.Env):
    """
    Normal driving environment for training a defensive AV.

    Reward: collision avoidance + lane keeping + speed maintenance.
    No adversarial NPC -- just normal IDM traffic.

    The trained policy can later be used as the ego vehicle in adversarial
    scenario evaluation, providing a meaningful "victim" baseline.
    """

    metadata = {"render_modes": ["human", "none"]}

    def __init__(
        self,
        lanes_count: int = 3,
        vehicles_count: int = 15,
        duration: int = 200,
        simulation_frequency: int = 10,
        policy_frequency: int = 10,
        render_mode: str = "none",
        # Reward weights (configurable via YAML)
        collision_penalty: float = -10.0,
        lane_keeping_bonus: float = 0.1,
        speed_bonus: float = 0.1,
        target_speed_low: float = 20.0,
        target_speed_high: float = 30.0,
    ):
        """
        Args:
            lanes_count: Number of highway lanes.
            vehicles_count: Number of IDM-controlled NPC vehicles.
            duration: Episode duration in policy steps.
            simulation_frequency: Highway-env physics updates per second.
            policy_frequency: Policy decisions per second.
            render_mode: "human" for visualization, "none" for headless.
            collision_penalty: Reward for collision (negative).
            lane_keeping_bonus: Max per-step reward for staying in lane center.
            speed_bonus: Per-step reward/penalty for speed target compliance.
            target_speed_low: Lower bound of target speed range (m/s).
            target_speed_high: Upper bound of target speed range (m/s).
        """
        super().__init__()

        _try_import_highway_env()

        # Environment parameters
        self._lanes_count = lanes_count
        self._vehicles_count = vehicles_count
        self._duration = duration
        self._sim_freq = simulation_frequency
        self._policy_freq = policy_frequency
        self.render_mode = render_mode

        # Reward parameters
        self._collision_penalty = collision_penalty
        self._lane_keeping_bonus = lane_keeping_bonus
        self._speed_bonus = speed_bonus
        self._target_speed_low = target_speed_low
        self._target_speed_high = target_speed_high

        # Derived constants
        self._lane_width: float = 4.0  # highway-env default lane width (m)

        # Internal highway-env environment (created on first reset)
        self._inner_env: Optional[gymnasium.Env] = None

        # Observation: 5 vehicles x 5 features (x, y, vx, vy, heading), flattened
        self._n_vehicles_obs: int = 5
        self._n_features: int = 5
        obs_dim = self._n_vehicles_obs * self._n_features
        self.observation_space = spaces.Box(
            low=-np.ones(obs_dim, dtype=np.float32),
            high=np.ones(obs_dim, dtype=np.float32),
            dtype=np.float32,
        )

        # Action: [acceleration, steering] normalized to [-1, 1]
        self.action_space = spaces.Box(
            low=np.array([-1.0, -1.0], dtype=np.float32),
            high=np.array([1.0, 1.0], dtype=np.float32),
            dtype=np.float32,
        )

        # Episode tracking
        self._step_count: int = 0

    # ------------------------------------------------------------------
    # Internal environment creation
    # ------------------------------------------------------------------
    def _make_inner_env(self) -> gymnasium.Env:
        """Create the underlying highway-env environment for normal driving."""
        import gymnasium as gym

        config = {
            "lanes_count": self._lanes_count,
            "vehicles_count": self._vehicles_count,
            "duration": self._duration,
            "simulation_frequency": self._sim_freq,
            "policy_frequency": self._policy_freq,
            # Disable ALL built-in rewards — we compute our own
            "collision_reward": 0,
            "right_lane_reward": 0,
            "high_speed_reward": 0,
            "lane_change_reward": 0,
            "reward_speed_range": [0, 100],
            "normalize_reward": False,
            "action": {
                "type": "ContinuousAction",
                "acceleration_range": [-5.0, 5.0],
                "steering_range": [-0.3, 0.3],
            },
            "observation": {
                "type": "Kinematics",
                "vehicles_count": self._n_vehicles_obs,
                "features": ["x", "y", "vx", "vy", "heading"],
                "normalize": True,
            },
        }

        # highway-env expects render_mode=None for headless, not "none"
        rm = self.render_mode if self.render_mode in ("human", "rgb_array") else None
        env = gym.make("highway-v0", render_mode=rm, config=config)
        return env

    # ------------------------------------------------------------------
    # Gymnasium interface
    # ------------------------------------------------------------------
    def reset(
        self, *, seed: Optional[int] = None, options: Optional[dict] = None
    ) -> Tuple[np.ndarray, dict]:
        super().reset(seed=seed)

        if self._inner_env is None:
            self._inner_env = self._make_inner_env()

        obs_raw, info = self._inner_env.reset(seed=seed)
        self._step_count = 0

        obs = self._flatten_obs(obs_raw)
        return obs, info

    def step(self, action: np.ndarray) -> Tuple[np.ndarray, float, bool, bool, dict]:
        obs_raw, _reward_unused, terminated, truncated, info = self._inner_env.step(
            action
        )
        self._step_count += 1

        obs = self._flatten_obs(obs_raw)
        reward, reward_components = self._compute_defensive_reward(info)
        info["reward_components"] = reward_components
        info["step_count"] = self._step_count

        return obs, reward, terminated, truncated, info

    def close(self):
        if self._inner_env is not None:
            self._inner_env.close()
            self._inner_env = None

    def render(self):
        if self._inner_env is not None:
            return self._inner_env.render()
        return None

    # ------------------------------------------------------------------
    # Observation processing
    # ------------------------------------------------------------------
    def _flatten_obs(self, obs_raw: np.ndarray) -> np.ndarray:
        """Flatten the Kinematics observation matrix to a 1D vector.

        highway-env returns shape (n_vehicles, n_features).
        We flatten and clip to observation_space bounds.
        """
        flat = obs_raw.flatten().astype(np.float32)
        expected_dim = self._n_vehicles_obs * self._n_features
        if flat.shape[0] < expected_dim:
            # Pad with zeros if fewer vehicles visible
            flat = np.concatenate(
                [flat, np.zeros(expected_dim - flat.shape[0], dtype=np.float32)]
            )
        elif flat.shape[0] > expected_dim:
            flat = flat[:expected_dim]
        return np.clip(flat, -1.0, 1.0)

    # ------------------------------------------------------------------
    # Reward computation
    # ------------------------------------------------------------------
    def _compute_defensive_reward(
        self, info: dict
    ) -> Tuple[float, Dict[str, float]]:
        """
        Compute the defensive driving reward.

        Components:
            R_collision:    Large penalty on crash (terminal).
            R_lane_keeping: Reward for staying near lane center.
            R_speed:        Reward for maintaining target speed range.

        Returns:
            (total_reward, component_dict)
        """
        ego = self._inner_env.unwrapped.vehicle
        r_collision = 0.0
        r_lane = 0.0
        r_speed = 0.0

        # --- Collision penalty ---
        crashed = getattr(ego, "crashed", False)
        if crashed:
            r_collision = self._collision_penalty

        # --- Lane keeping ---
        # Compute lateral offset from lane center
        try:
            # highway-env stores the lane the ego is on; compute offset
            lane_index = ego.lane_index
            lane = ego.road.network.get_lane(lane_index)
            # Position along lane (longitudinal, lateral)
            _, lateral_offset = lane.local_coordinates(ego.position)
            half_width = self._lane_width / 2.0
            # Normalize: 0 at edge, 1 at center
            lane_centering = max(0.0, 1.0 - abs(lateral_offset) / half_width)
            r_lane = self._lane_keeping_bonus * lane_centering
        except Exception:
            # Fallback: no lane info available
            r_lane = 0.0

        # --- Speed maintenance ---
        speed = float(ego.speed)
        if self._target_speed_low <= speed <= self._target_speed_high:
            r_speed = self._speed_bonus
        else:
            r_speed = -self._speed_bonus

        total = r_collision + r_lane + r_speed

        components = {
            "r_collision": r_collision,
            "r_lane_keeping": r_lane,
            "r_speed": r_speed,
        }
        return total, components
